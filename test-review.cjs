const assert=require('node:assert/strict');
const M=require('./dist/review-model.js');
const note={id:'one',date:'2026-10-08',text:'［美國］🇺🇸\nAI 與醫療費用',links:[]};
const collected=M.collect([{id:'a',name:'AI',entries:[note]},{id:'b',name:'財政',entries:[{...note}]}]);
assert.equal(collected.length,1);
assert.equal(collected[0].topics.length,2);
assert.equal(collected[0].title,'AI 與醫療費用');
assert.deepEqual(collected[0].regionIds,['us']);
assert.equal(M.weekStart('2026-10-17'),'2026-10-12');
assert(M.inWeek(collected[0],'2026-10-05'));
assert(!M.inWeek(collected[0],'2026-10-12'));
const late=M.collect([{id:'a',name:'AI',entries:[{...note,createdAt:'2026-10-11T16:01:00Z'}]}])[0];
assert.equal(late.statDate,'2026-10-12');
assert.deepEqual(M.inferRegions({...note,region:'europe'}),['europe']);
assert.deepEqual(M.inferRegions({text:'人工智慧與責任'}),['global']);
assert(M.options([], '2026-10-17').includes('2026-10-05'));
const actual=M.collect(require('./issues.json'));
assert(actual.length<=require('./issues.json').flatMap(i=>i.entries).length);
console.log(`閱讀模型檢查通過；真實記事去重後 ${actual.length} 篇`);
